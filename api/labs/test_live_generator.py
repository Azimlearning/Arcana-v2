PASSAGE = (
    "Using the permutation generated by ChatGPT we optimise the student. "
    "RankNet is a pairwise loss that measures the correctness of relative passage orders: L = sum log(1 + exp(sj - si))."
)


class StubLLM:
    def __init__(self, text: str | None = None, error: Exception | None = None):
        self.text, self.error, self.requests = text, error, []

    async def complete(self, request):
        self.requests.append(request)
        if self.error is not None:
            raise self.error
        return SimpleNamespace(text=self.text)


@pytest.fixture
def world(tmp_path: Path):
    docs = SqliteDocStore(make_engine(tmp_path / "docs.db"))
    docs.put_document(Document("d1", "A Ranking Paper", "d1.pdf", "ready", 1, None, "2026-10-15"))
    docs.put_chunks([Chunk("c1", "d1", 0, 16, PASSAGE)])
    return docs, SqliteLabStore(tmp_path / "labs.db")


def test_the_prompt_carries_the_passage_and_ranges_but_not_the_reference_cases():
    contract = ranknet_contract()
    prompt = lab_prompt(contract, PASSAGE)
    assert "RankNet is a pairwise loss" in prompt and "p.si" in prompt and "-4 to 4" in prompt
    for case in contract.cases:  # the verifier's expected values are not leaked to the model it tests
        assert repr(case.expected) not in prompt and f"{case.expected:g}" not in prompt
    assert "Math.log1p" not in SYSTEM or "log1p" in SYSTEM  # the language is described, not an answer


def test_a_fenced_reply_is_unwrapped_and_anything_else_is_left_to_the_checker():
    assert strip_fence("```js\nfunction lab(p) { return 1; }\n```") == "function lab(p) { return 1; }"
    assert strip_fence("function lab(p) { return 1; }") == "function lab(p) { return 1; }"
    assert strip_fence("here you go: function lab(p) { return 1; }").startswith("here you go")


def test_a_correct_reply_becomes_a_lab_through_the_verifier(world):
    docs, labs = world
    llm = StubLLM(RANKNET_SOURCE)
    generator = LiveLabGenerator(llm, docs)  # type: ignore[arg-type]
    _, blocks = compose_lab(docs, labs, generator, "ranknet_pairwise_loss")
    assert blocks[0].meta.status == "ready" and generator.generator_id == LIVE_PROMPT_VERSION
    assert [r.purpose for r in llm.requests] == ["generate"]  # one call, booked under its own purpose
    assert labs.counts() == {"verified": 1}


def test_a_hostile_or_wrong_reply_is_rejected_and_kept_only_as_a_record(world):
    docs, labs = world
    for reply in ("function lab(p) { return fetch('http://x'); }", "function lab(p) { return 1; }", "I cannot do that."):
        _, blocks = compose_lab(docs, labs, LiveLabGenerator(StubLLM(reply), docs), "ranknet_pairwise_loss")  # type: ignore[arg-type]
        assert blocks[0].meta.status == "error"
    assert labs.counts() == {"rejected": 3} and labs.find_servable("ranknet_pairwise_loss") is None


def test_the_spend_cap_refusing_a_call_is_an_error_block_not_a_crash(world):
    docs, labs = world
    generator = LiveLabGenerator(StubLLM(error=SpendCapExceeded("cap reached")), docs)  # type: ignore[arg-type]
    _, blocks = compose_lab(docs, labs, generator, "ranknet_pairwise_loss")
    assert blocks[0].meta.status == "error"
    assert blocks[0].meta.error is not None and blocks[0].meta.error.code == "spend_cap_exceeded"  # type: ignore[union-attr]
    assert labs.counts() == {}


def test_every_contract_can_be_prompted():
    for make in CONTRACTS.values():
        contract = make()
        assert contract.title in lab_prompt(contract, "a passage")


@pytest.mark.asyncio
async def test_called_from_an_anyio_worker_the_call_runs_on_the_apps_own_loop(world):
    """Under FastAPI a sync route runs in an AnyIO worker; the model call must go back to the app's loop, where the provider clients live."""
    import asyncio

    from anyio import to_thread

    docs, _ = world
    seen: list[asyncio.AbstractEventLoop] = []

    class LoopRecordingLLM:
        async def complete(self, request):
            seen.append(asyncio.get_running_loop())
            return SimpleNamespace(text=RANKNET_SOURCE)

    generator = LiveLabGenerator(LoopRecordingLLM(), docs)  # type: ignore[arg-type]
    source = await to_thread.run_sync(generator.generate, ranknet_contract())
    assert source == RANKNET_SOURCE and seen == [asyncio.get_running_loop()]
