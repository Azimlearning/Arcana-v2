CONTRACT = ranknet_contract()
LAB = "ranknet_pairwise_loss"
PASSAGE = (
    "Using the permutation generated by ChatGPT we optimise the student. "
    "RankNet is a pairwise loss that measures the correctness of relative passage orders: L = sum log(1 + exp(sj - si))."
)


@pytest.fixture
def world(tmp_path: Path):
    docs = SqliteDocStore(make_engine(tmp_path / "docs.db"))
    docs.put_document(Document("d1", "A Ranking Paper", "d1.pdf", "ready", 1, None, "2026-10-08"))
    docs.put_chunks([Chunk("c1", "d1", 0, 16, PASSAGE)])
    return docs, SqliteLabStore(tmp_path / "labs.db")


def made(docs, labs, generator=None):
    generator = generator or FakeLabGenerator()
    _, blocks = compose_lab(docs, labs, generator, LAB)
    return blocks[0], generator


def lab_id(labs) -> str:
    stored = labs.find_servable(LAB)
    assert stored is not None
    return stored.lab_id


def test_the_transition_table_is_closed_and_terminal_states_have_no_way_out():
    states = list(lifecycle.ALLOWED)
    for a, b in product(states, states):
        assert lifecycle.can_transition(a, b) == (b in lifecycle.ALLOWED[a])
    assert lifecycle.ALLOWED["evicted"] == frozenset() and lifecycle.ALLOWED["rejected"] == frozenset()
    assert lifecycle.ALLOWED["stale"] == {"verified", "evicted"}
    assert not lifecycle.can_transition("verified", "promoted")  # promotion goes through an audit
    assert not lifecycle.can_transition("evicted", "verified")
    assert lifecycle.SERVABLE == {"verified", "cached", "audited", "promoted"}


def test_a_fresh_lab_is_verified_and_an_illegal_move_is_refused(world):
    docs, labs = world
    made(docs, labs)
    assert labs.counts() == {"verified": 1}
    with pytest.raises(ValueError):
        labs.transition(lab_id(labs), "promoted", "skipping the audit")
    with pytest.raises(ValueError):
        labs.transition("no-such-lab", "cached", "x")


def test_the_second_request_is_served_from_the_store_without_the_generator(world):
    docs, labs = world
    first, generator = made(docs, labs)
    second, _ = made(docs, labs, generator)
    assert generator.calls == [LAB]  # the generator was asked once
    assert first.meta.status == second.meta.status == "ready"
    assert first.data.sourceSha256 == second.data.sourceSha256  # type: ignore[union-attr]
    assert labs.counts() == {"cached": 1}
    # with no generator at all (live mode before a live generator exists) a stored lab is still served, after being verified again
    _, blocks = compose_lab(docs, labs, None, LAB)
    assert blocks[0].meta.status == "ready"


def test_a_stored_lab_that_no_longer_verifies_is_evicted_and_never_served(world, monkeypatch):
    docs, labs = world
    first, _ = made(docs, labs)
    stored_id = lab_id(labs)
    import api.agents.compose as compose

    real = compose.verify
    calls = {"n": 0}

    def failing_once(contract, source):
        calls["n"] += 1
        if calls["n"] == 1:  # the reuse check
            raise VerificationFailed("finite", "the function returned nan")
        return real(contract, source)

    monkeypatch.setattr(compose, "verify", failing_once)
    block, _ = made(docs, labs)
    # evicted, and the same source is not stored or served again: an error block that names the store, not a lab
    assert labs.counts() == {"evicted": 1}
    assert labs.find_servable(LAB) is None and labs.get(stored_id) is None
    assert block.meta.status == "error"
    with pytest.raises(ValidationFailed):  # the earlier block no longer derives from a servable record
        validate_block(first.model_dump(), docs, labs=labs)


def test_an_audit_passes_a_good_lab_and_evicts_one_whose_evidence_is_gone(world, tmp_path):
    docs, labs = world
    made(docs, labs)
    assert audit_lab(labs, docs, lab_id(labs)) == "audited"
    assert labs.counts() == {"audited": 1}
    # the same lab, against a document set that no longer states the formula
    empty = SqliteDocStore(make_engine(tmp_path / "empty.db"))
    assert audit_lab(labs, empty, lab_id(labs)) == "evicted"
    assert labs.counts() == {"evicted": 1}
    assert audit_lab(labs, docs, "no-such-lab") == "missing"


def test_an_audited_lab_delivered_enough_times_is_promoted_and_candidates_are_reported(world):
    docs, labs = world
    made(docs, labs)
    stored_id = lab_id(labs)
    assert audit_lab(labs, docs, stored_id) == "audited"
    for _ in range(lifecycle.PROMOTE_AFTER_DELIVERIES):
        made(docs, labs)
    assert labs.counts() == {"promoted": 1}
    assert labs.crystallisation_candidates() == []  # one promoted lab for the contract is not a repeated pattern
    # a second promoted lab of the same contract (a different but valid source) makes it a candidate; nothing is built from the list
    other = RANKNET_SOURCE.replace("{\n", "{\n  ", 1)
    assert other != RANKNET_SOURCE
    artifact = verify(CONTRACT, other)
    labs.put_verified(artifact)
    assert labs.get(artifact.lab_id) is not None
    labs.transition(artifact.lab_id, "audited", "test")
    labs.transition(artifact.lab_id, "promoted", "test")
    assert labs.crystallisation_candidates() == [LAB]


def test_a_template_contract_or_generator_change_marks_stale_and_a_stale_lab_is_not_served_until_verified_again(world):
    docs, labs = world
    made(docs, labs)
    fingerprints = {LAB: contract_sha256(CONTRACT)}
    assert labs.mark_stale(TEMPLATE_VERSION, fingerprints, "fake-lab-1") == 0  # nothing changed
    assert labs.mark_stale(TEMPLATE_VERSION, {LAB: "another fingerprint"}, "fake-lab-1") == 1
    assert labs.counts() == {"stale": 1} and labs.find_servable(LAB) is None
    # asked again: regenerated, verified under the current template, and the stale record is revalidated (same id), not duplicated
    block, generator = made(docs, labs)
    assert generator.calls == [LAB] and block.meta.status == "ready"
    assert labs.counts() == {"verified": 1}


def test_a_changed_generator_marks_a_lab_made_by_the_old_one_stale(world):
    docs, labs = world
    made(docs, labs)
    assert labs.mark_stale(TEMPLATE_VERSION, {LAB: contract_sha256(CONTRACT)}, "fake-lab-2") == 1
    assert labs.counts() == {"stale": 1}


def test_an_older_database_without_the_lifecycle_columns_opens_and_keeps_its_labs(tmp_path: Path):
    path = tmp_path / "labs.db"
    artifact = verify(CONTRACT, RANKNET_SOURCE)
    with sqlite3.connect(path) as db:
        db.execute(
            "CREATE TABLE labs (lab_id TEXT PRIMARY KEY, contract_id TEXT NOT NULL, contract_sha256 TEXT NOT NULL, source TEXT NOT NULL, "
            "source_sha256 TEXT NOT NULL, template_version INTEGER NOT NULL, checked TEXT NOT NULL, state TEXT NOT NULL, reason TEXT, "
            "created_at TEXT NOT NULL)"
        )
        db.execute(
            "INSERT INTO labs VALUES (?, ?, ?, ?, ?, ?, ?, 'verified', NULL, '2026-10-08')",
            (
                artifact.lab_id,
                artifact.contract_id,
                artifact.contract_sha256,
                artifact.source,
                artifact.source_sha256,
                artifact.template_version,
                '{"reference_cases": 4, "properties": 5, "fuzz_cases": 200, "grid_points": 4225}',
            ),
        )
    labs = SqliteLabStore(path)  # migrates in place
    assert labs.get(artifact.lab_id) is not None
    labs.transition(artifact.lab_id, "cached", "after migration")
    assert labs.counts() == {"cached": 1}


def test_a_timeout_under_load_does_not_evict_a_good_lab(world, monkeypatch):
    docs, labs = world
    made(docs, labs)
    import api.agents.compose as compose

    real = compose.verify
    calls = {"n": 0}

    def slow_once(contract, source):
        calls["n"] += 1
        if calls["n"] == 1:  # the reuse check, on a loaded machine
            raise VerificationFailed("run", "the function did not finish in time")
        return real(contract, source)

    monkeypatch.setattr(compose, "verify", slow_once)
    block, _ = made(docs, labs)
    assert block.meta.status == "ready"
    assert labs.counts() == {"verified": 1}  # still servable: the machine, not the lab


def test_an_audit_marks_a_record_stale_when_it_is_not_the_current_template(world):
    docs, labs = world
    made(docs, labs)
    stored_id = lab_id(labs)
    with sqlite3.connect(labs._path) as db:  # a record made under an older template that mark_stale has not seen yet
        db.execute("UPDATE labs SET template_version = 1 WHERE lab_id = ?", (stored_id,))
    assert audit_lab(labs, docs, stored_id) == "stale"
    assert labs.counts() == {"stale": 1} and labs.get(stored_id) is None


def test_flagging_twice_is_not_an_error_and_a_flagged_lab_stays_out(world):
    docs, labs = world
    made(docs, labs)
    stored_id = lab_id(labs)
    labs.flag(stored_id, "first")
    labs.flag(stored_id, "second request failing at once")
    assert labs.counts() == {"evicted": 1} and labs.get(stored_id) is None
