"""The delivery gate for `VerifiedLab` (P4 V4, D-36, hard constraint 3).

A lab block is delivered only if it equals what the stored, verified record derives. These tests build the real thing (a passage that states
the RankNet formula, the fake generator, the verifier) and then plant every way of getting around the gate: a forged block, a changed byte, a
changed hash, a stale template version, an unknown lab, an unverified (rejected) lab, a missing store, a partial block, and each
placeholder carrying content. They also check that the builder refuses anything but a minted artifact and that no route or module can
emit a lab except through `validate_block`.
"""

