def test_only_the_gate_modules_know_how_to_build_or_name_a_lab_block():
    """Every module under `api/` (tests aside) that names the `VerifiedLab` block type is one of the gate's own. A new route or agent that
    builds one would have to be added here on purpose, and so reviewed."""
    root = Path(__file__).resolve().parents[2] / "api"
    allowed = {
        "genui/generated.py",
        "genui/builders.py",
        "genui/validate.py",
        "genui/lab_catalog.py",
        "agents/compose.py",
        "labs/evidence.py",
        "routes/labs.py",
    }
    named = set()
    for path in root.rglob("*.py"):
        rel = path.relative_to(root).as_posix()
        if "/test_" in "/" + rel or rel.startswith("test_"):
            continue
        if re.search(r"""["']VerifiedLab["']""", path.read_text(encoding="utf-8")):
            named.add(rel)
    assert named <= allowed, (
        f"modules that name a VerifiedLab and are not gate modules: {sorted(named - allowed)}"
    )


def test_every_route_that_returns_a_lab_does_it_through_compose_lab(tmp_path: Path):
    settings = Settings(_env_file=None, arcana_data_dir=tmp_path / "data")  # pyright: ignore[reportCallIssue]
    with TestClient(create_app(settings)) as client:
        container = client.app.state.container  # type: ignore[attr-defined]
        container.docs.put_document(
            Document("d1", "A Ranking Paper", "d1.pdf", "ready", 1, None, "2026-10-08")
        )
        container.docs.put_chunks([Chunk("c1", "d1", 0, 16, PASSAGE)])
        made = client.post("/labs", json={"contractId": "ranknet_pairwise_loss"})
        assert made.status_code == 200
        block = made.json()["blocks"][0]
        assert (block["type"], block["meta"]["status"]) == ("VerifiedLab", "ready")
        assert block["data"]["source"] == RANKNET_SOURCE
        assert container.lab_store.get(block["data"]["labId"]) is not None
        assert client.post("/labs", json={"contractId": "no_such_lab"}).status_code == 404
        assert (
            client.post(
                "/labs", json={"contractId": "ranknet_pairwise_loss", "source": "code"}
            ).status_code
            == 422
        )  # no code in
        assert client.post("/labs", json={}).status_code == 422
        too_big = client.post(
            "/labs",
            content=b"x" * 5000,
            headers={"content-type": "application/json", "content-length": "5000"},
        )
        assert too_big.status_code == 413
        # a lab block never comes out of the other views
        assert all(b["type"] != "VerifiedLab" for b in client.get("/workspace").json()["blocks"])
        assert all(b["type"] != "VerifiedLab" for b in client.get("/vault/notes").json()["blocks"])


