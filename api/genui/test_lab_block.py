CONTRACT = ranknet_contract()
PASSAGE = (
    "Using the permutation generated by ChatGPT we optimise the student. "
    "RankNet is a pairwise loss that measures the correctness of relative passage orders: L = sum log(1 + exp(sj - si))."
)


@pytest.fixture
def world(tmp_path: Path):
    docs = SqliteDocStore(make_engine(tmp_path / "docs.db"))
    docs.put_document(Document("d1", "A Ranking Paper", "d1.pdf", "ready", 1, None, "2026-10-08"))
    docs.put_chunks([Chunk("c1", "d1", 0, 16, PASSAGE)])
    return docs, SqliteLabStore(tmp_path / "labs.db")


def good_block(docs, labs):
    artifact = verify(CONTRACT, RANKNET_SOURCE)
    labs.put_verified(artifact)
    citation = find_source(docs, CONTRACT)
    assert citation is not None
    return verified_lab("lab", "ready", artifact=artifact, contract=CONTRACT, citation=citation)


def test_a_lab_made_through_every_gate_is_delivered_with_its_citation_and_counts(world):
    docs, labs = world
    layout, blocks = compose_lab(docs, labs, FakeLabGenerator(), "ranknet_pairwise_loss")
    block = blocks[0]
    assert (block.type, block.meta.status, block.id) == ("VerifiedLab", "ready", "lab")
    d = block.data  # type: ignore[union-attr]
    assert d.source == RANKNET_SOURCE and len(d.sourceSha256) == 64 and d.templateVersion == 2
    assert (
        d.checked.referenceCases,
        d.checked.properties,
        d.checked.fuzzCases,
        d.checked.gridPoints,
    ) == (4, 5, 200, 4225)
    assert d.gridSteps == 64
    assert (
        d.citations[0].quote.startswith("RankNet is a pairwise loss") and d.citations[0].page == 16
    )
    assert d.citations[0].docTitle == "A Ranking Paper"
    assert [p.panel for p in layout.placements] == ["studio"]
    assert validate_block(block.model_dump(), docs, labs=labs).type == "VerifiedLab"


@pytest.mark.parametrize("forge", list(FORGERIES.values()), ids=list(FORGERIES))
def test_the_gate_refuses_every_planted_forgery(world, forge):
    docs, labs = world
    raw = good_block(docs, labs)
    forge(raw["data"])
    with pytest.raises(ValidationFailed) as refused:
        validate_block(raw, docs, labs=labs)
    assert refused.value.issues


def test_a_lab_with_no_store_to_check_against_is_refused(world):
    docs, labs = world
    with pytest.raises(ValidationFailed, match="content validation"):
        validate_block(good_block(docs, labs), docs)


def test_a_lab_that_was_rejected_is_never_delivered(world):
    docs, labs = world
    raw = good_block(docs, labs)
    labs.put_rejected(CONTRACT.id, "function lab(p) { return 1; }", "reference_cases", "wrong")
    raw["data"]["labId"] = (
        f"rejected-{__import__('hashlib').sha256(b'function lab(p) { return 1; }').hexdigest()[:16]}"
    )
    with pytest.raises(ValidationFailed):
        validate_block(raw, docs, labs=labs)


def test_a_missing_source_passage_refuses_the_block_the_evidence_precondition(world):
    docs, labs = world
    raw = good_block(docs, labs)
    docs.put_chunks(
        [
            Chunk(
                "c1",
                "d1",
                0,
                16,
                "A passage that no longer states the formula in any words at all.",
            )
        ]
    )
    with pytest.raises(ValidationFailed) as refused:
        validate_block(raw, docs, labs=labs)
    assert refused.value.issues[0].path == "data.citations"


def test_a_store_that_cannot_be_read_refuses_instead_of_crashing(world, monkeypatch):
    docs, labs = world
    raw = good_block(docs, labs)

    def boom(_lab_id):
        raise RuntimeError("disk")

    monkeypatch.setattr(labs, "get", boom)
    with pytest.raises(ValidationFailed, match="content validation"):
        validate_block(raw, docs, labs=labs)


def test_partial_is_refused_and_placeholders_carry_nothing(world):
    docs, labs = world
    for status in ("empty", "loading"):
        assert validate_block(verified_lab("lab", status), docs, labs=labs).meta.status == status
    partial = good_block(docs, labs)
    partial["meta"]["status"] = "partial"
    with pytest.raises(ValidationFailed):
        validate_block(partial, docs, labs=labs)
    loaded = good_block(docs, labs)
    loaded["meta"]["status"] = "loading"  # a placeholder that still carries code
    with pytest.raises(ValidationFailed):
        validate_block(loaded, docs, labs=labs)


def test_the_builder_accepts_only_a_minted_artifact(world):
    docs, labs = world
    stored = labs.put_verified(verify(CONTRACT, RANKNET_SOURCE))
    citation = find_source(docs, CONTRACT)
    for not_minted in (stored, None, {"source": RANKNET_SOURCE}, object()):
        with pytest.raises(TypeError):
            verified_lab("lab", "ready", artifact=not_minted, contract=CONTRACT, citation=citation)  # type: ignore[arg-type]
    with pytest.raises(TypeError):
        verified_lab(
            "lab",
            "ready",
            artifact=verify(CONTRACT, RANKNET_SOURCE),
            contract=None,
            citation=citation,
        )


def test_a_defective_function_never_becomes_a_block_and_the_reason_names_the_stage(world):
    docs, labs = world
    cases = {
        "function lab(p) { return fetch('x'); }": "check",
        "function lab(p) { return p.sj - p.si; }": "reference_cases",
        "function lab(p) { return 1 / 0; }": "finite",
    }
    for source, stage in cases.items():
        _, blocks = compose_lab(
            docs, labs, FakeLabGenerator({"ranknet_pairwise_loss": source}), "ranknet_pairwise_loss"
        )
        block = blocks[0]
        assert (block.type, block.meta.status) == ("VerifiedLab", "error")
        assert block.meta.error is not None and block.meta.error.issues[0].path == stage
        assert block.data.source == ""  # type: ignore[union-attr]  # no code travels with a failure
    assert len(labs.rejected()) == 3 and labs.get("ranknet_pairwise_loss-" + "0" * 12) is None


def test_with_no_stated_formula_there_is_no_lab_and_with_no_generator_it_says_so(world):
    docs, labs = world
    docs.put_chunks(
        [
            Chunk(
                "c1",
                "d1",
                0,
                16,
                "A passage with nothing about that loss in it, only prose around it here.",
            )
        ]
    )
    _, blocks = compose_lab(docs, labs, FakeLabGenerator(), "ranknet_pairwise_loss")
    assert blocks[0].meta.status == "empty"
    docs.put_chunks([Chunk("c1", "d1", 0, 16, PASSAGE)])
    _, blocks = compose_lab(docs, labs, None, "ranknet_pairwise_loss")
    assert blocks[0].meta.status == "error" and "not available" in blocks[0].meta.error.message  # type: ignore[union-attr]
    with pytest.raises(NotFound):
        compose_lab(docs, labs, FakeLabGenerator(), "no_such_lab")


def test_nothing_unverified_comes_back_even_if_validate_block_were_the_only_guard(
    world, monkeypatch
):
    docs, labs = world

    def refuse(*_args, **_kwargs):
        raise ValidationFailed("refused", [])

    monkeypatch.setattr("api.agents.compose.validate_block", refuse)
    with pytest.raises(ValidationFailed):
        compose_lab(
            docs, labs, FakeLabGenerator(), "ranknet_pairwise_loss"
        )  # no block is returned around the validator


